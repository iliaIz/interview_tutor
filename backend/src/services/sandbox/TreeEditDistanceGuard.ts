/**
 * TreeEditDistanceGuard.ts
 *
 * Implements pedagogical anti-cheat and solution leak prevention.
 * Uses normalized AST/syntactic tokenization and normalized Levenshtein edit distance:
 *
 *   Sim_{AST}(S_{target}, S_{chunk}) = 1 - (Dist_{Levenshtein}(T_{target}, T_{chunk}) / max(|T_{target}|, |T_{chunk}|))
 *
 * If similarity >= leakThreshold (default 0.40) in Senior / Socratic modes,
 * the direct solution code is intercepted and replaced with a pedagogical Socratic scaffold.
 */

export interface CodeLeakCheckResult {
  leakDetected: boolean;
  maxSimilarity: number;
  redactedText: string;
  matchedSnippetsCount: number;
}

export class TreeEditDistanceGuard {
  private static readonly JAVA_KEYWORDS = new Set([
    'abstract', 'assert', 'boolean', 'break', 'byte', 'case', 'catch', 'char', 'class', 'const',
    'continue', 'default', 'do', 'double', 'else', 'enum', 'extends', 'final', 'finally', 'float',
    'for', 'goto', 'if', 'implements', 'import', 'instanceof', 'int', 'interface', 'long', 'native',
    'new', 'package', 'private', 'protected', 'public', 'return', 'short', 'static', 'strictfp',
    'super', 'switch', 'synchronized', 'this', 'throw', 'throws', 'transient', 'try', 'void',
    'volatile', 'while', 'record', 'var', 'yield', 'sealed', 'permits'
  ]);

  private static readonly TESTING_KEYWORDS = new Set([
    'assertThat', 'assertThatThrownBy', 'isEqualTo', 'isTrue', 'isFalse', 'isNull', 'isNotNull',
    'isEqualByComparingTo', 'isInstanceOf', 'hasMessage', 'contains', 'hasSize', 'verify', 'times',
    'never', 'any', 'anyString', 'mock', 'when', 'thenReturn', 'thenThrow', 'doNothing', 'ArgumentCaptor',
    'capture', 'getValue', 'await', 'untilAsserted', 'pollInterval', 'atMost', 'Duration'
  ]);

  /**
   * Tokenizes Java code into a stream of normalized syntactic tokens:
   * Keywords and testing primitives are kept intact;
   * Custom variable/method identifiers are normalized to '$ID' to detect structural plagiarism;
   * Literals are normalized to '$LIT';
   * Punctuation and operators are preserved.
   */
  public static tokenize(code: string): string[] {
    if (!code) return [];

    // 1. Remove comments
    const noComments = code
      .replace(/\/\*[\s\S]*?\*\//g, ' ')
      .replace(/\/\/.*$/gm, ' ');

    // 2. Tokenize by identifiers, strings, numbers, and operators
    const rawTokens = noComments.match(/[a-zA-Z_$][a-zA-Z0-9_$]*|"[^"]*"|'[^']*'|==|!=|<=|>=|&&|\|\||->|::|\+\+|--|\+=|-=|\*=|\/=|[{}\[\](),;.<>=!+\-*\/%&|^~?:]|\d+/g) || [];

    const normalized: string[] = [];
    for (const tok of rawTokens) {
      if (this.JAVA_KEYWORDS.has(tok) || this.TESTING_KEYWORDS.has(tok)) {
        normalized.push(tok);
      } else if (tok.startsWith('"') || tok.startsWith("'") || /^\d+$/.test(tok)) {
        normalized.push('$LIT');
      } else if (/^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(tok)) {
        normalized.push('$ID');
      } else {
        normalized.push(tok);
      }
    }
    return normalized;
  }

  /**
   * Fast Levenshtein distance on token arrays using two-row memory buffer O(min(N, M)).
   */
  public static tokenLevenshtein(tokensA: string[], tokensB: string[]): number {
    if (tokensA.length === 0) return tokensB.length;
    if (tokensB.length === 0) return tokensA.length;

    let s1 = tokensA;
    let s2 = tokensB;
    if (s1.length > s2.length) {
      s1 = tokensB;
      s2 = tokensA;
    }

    const n = s1.length;
    const m = s2.length;
    let prev = new Int32Array(n + 1);
    let curr = new Int32Array(n + 1);

    for (let i = 0; i <= n; i++) {
      prev[i] = i;
    }

    for (let j = 1; j <= m; j++) {
      curr[0] = j;
      const tok2 = s2[j - 1];
      for (let i = 1; i <= n; i++) {
        const cost = s1[i - 1] === tok2 ? 0 : 1;
        curr[i] = Math.min(
          curr[i - 1] + 1,       // insertion
          prev[i] + 1,           // deletion
          prev[i - 1] + cost     // substitution
        );
      }
      const tmp = prev;
      prev = curr;
      curr = tmp;
    }

    return prev[n];
  }

  /**
   * Calculates structural similarity in range [0.0, 1.0].
   */
  public static calculateSimilarity(codeA: string, codeB: string): number {
    const tokensA = this.tokenize(codeA);
    const tokensB = this.tokenize(codeB);

    if (tokensA.length === 0 || tokensB.length === 0) return 0.0;

    const maxLen = Math.max(tokensA.length, tokensB.length);
    const dist = this.tokenLevenshtein(tokensA, tokensB);
    return Math.max(0.0, 1.0 - dist / maxLen);
  }

  /**
   * Inspects text generated by AI. If a code block leaks significant portions of the target
   * canonical test or solution above the threshold, redacts it with pedagogical guidance.
   */
  public static guardResponse(
    aiResponseText: string,
    targetSolutionSources: string[],
    options: {
      leakThreshold?: number; // default 0.40
      isSocraticEnforced?: boolean; // e.g. Senior or FAANG mode
    } = {}
  ): CodeLeakCheckResult {
    const threshold = options.leakThreshold ?? 0.40;
    const isSocratic = options.isSocraticEnforced ?? true;

    if (!isSocratic || !targetSolutionSources || targetSolutionSources.length === 0) {
      return {
        leakDetected: false,
        maxSimilarity: 0,
        redactedText: aiResponseText,
        matchedSnippetsCount: 0
      };
    }

    // Extract code blocks from markdown (```java ... ``` or ``` ... ```)
    const codeBlockRegex = /```(?:java|typescript|javascript)?\s*([\s\S]*?)```/g;
    let leakDetected = false;
    let maxSimilarity = 0.0;
    let matchedSnippetsCount = 0;

    const redactedText = aiResponseText.replace(codeBlockRegex, (match, codeSnippet) => {
      // Ignore tiny 1-2 line trivial snippets
      const lines = codeSnippet.trim().split(/\r?\n/);
      if (lines.length < 3) return match;

      for (const targetSource of targetSolutionSources) {
        const sim = this.calculateSimilarity(codeSnippet, targetSource);
        if (sim > maxSimilarity) {
          maxSimilarity = sim;
        }

        if (sim >= threshold) {
          leakDetected = true;
          matchedSnippetsCount++;
          return (
            `\`\`\`java\n` +
            `// 💡 [Socratic Guard]: Прямое решение скрыто для тренировки навыка.\n` +
            `// Сформулируйте тест самостоятельно: какой входной параметр или граничное условие\n` +
            `// заставит тестируемый метод проявить дефект (RIPR: Reachability -> Infection -> Propagation)?\n` +
            `\`\`\``
          );
        }
      }

      return match;
    });

    return {
      leakDetected,
      maxSimilarity,
      redactedText,
      matchedSnippetsCount
    };
  }
}
